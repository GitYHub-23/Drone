/* =====================================================
 * HELPERS
 * ===================================================== */

static float clampf(
    float value,
    float minimum,
    float maximum
)
{
    if(value < minimum)
        return minimum;

    if(value > maximum)
        return maximum;

    return value;
}

static float absf(float value)
{
    return value < 0.0f ? -value : value;
}

/* =====================================================
 * STEP 21 - FAST BENCH TRIG HELPERS
 * =====================================================
 * Software floating point on 8 MHz Cortex-M0. No libm required.
 * arctan approximation is intended for diagnostic tilt estimates,
 * not precision inertial navigation or flight control.
 *
 * atan(z) ~= z * [pi/4 + 0.273*(1-z)] for 0 <= z <= 1.
 * Sign and quadrant are handled below.
 */

static float atan_ratio_bench(float z)
{
    /* z must be in [0,1]. */
    return z * (0.7853981634f + 0.273f * (1.0f - z));
}

static float atan2_bench_deg(float y, float x)
{
    float ax = absf(x);
    float ay = absf(y);
    float angle;

    if(ax < 0.000001f && ay < 0.000001f)
        return 0.0f;

    if(ax >= ay)
        angle = atan_ratio_bench(ay / ax);
    else
        angle = 1.5707963268f - atan_ratio_bench(ax / ay);

    if(x < 0.0f)
        angle = 3.1415926536f - angle;

    if(y < 0.0f)
        angle = -angle;

    return angle * RAD_TO_DEG;
}

/* Approximate hypot with two Newton iterations.
 * For this normalized IMU application it avoids sqrtf/libm.
 */
static float hypot_bench(float x, float y)
{
    float a = absf(x);
    float b = absf(y);
    float hi = a > b ? a : b;
    float lo = a > b ? b : a;
    float ratio, n2, root;

    if(hi < 0.000001f)
        return 0.0f;

    ratio = lo / hi;
    n2 = 1.0f + ratio * ratio;
    root = 1.0f + 0.4142135624f * ratio;
    root = 0.5f * (root + n2 / root);
    root = 0.5f * (root + n2 / root);
    return hi * root;
}

/* =====================================================
 * MOTOR HARDWARE LOCK
 * ===================================================== */

static void motor_hardware_off(void)
{
    RCC_AHBENR |= (1U << 17);
    RCC_APB2ENR |= (1U << 11);

    (void)RCC_AHBENR;
    (void)RCC_APB2ENR;

    /* Disable TIM1 */

    TIM1_BDTR = 0;
    TIM1_CCER = 0;
    TIM1_CR1 = 0;

    /* Motor pins LOW */

    BSRR(GA) = MOTOR_MASK << 16U;

    OTYPER(GA) &= ~MOTOR_MASK;

    PUPDR(GA) =
        (PUPDR(GA) & ~MOTOR_MODE_MASK) |
        (0xAAU << 16U);

    MODER(GA) =
        (MODER(GA) & ~MOTOR_MODE_MASK) |
        MOTOR_OUTPUT_MODES;

    TIM1_CCR1 = 0;
    TIM1_CCR2 = 0;
    TIM1_CCR3 = 0;
    TIM1_CCR4 = 0;

    TIM1_EGR = 1;
}

void SystemInit(void)
{
    motor_hardware_off();
}

static uint32_t motor_off_verified(void)
{
    return (
        ((MODER(GA) & MOTOR_MODE_MASK)
            == MOTOR_OUTPUT_MODES) &&

        ((OTYPER(GA) & MOTOR_MASK) == 0U) &&
        ((ODR(GA) & MOTOR_MASK) == 0U) &&

        TIM1_BDTR == 0U &&
        TIM1_CCER == 0U &&
        (TIM1_CR1 & 1U) == 0U &&

        TIM1_CCR1 == 0U &&
        TIM1_CCR2 == 0U &&
        TIM1_CCR3 == 0U &&
        TIM1_CCR4 == 0U
    );
}

