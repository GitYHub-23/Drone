static uint32_t clock_init(void)
{
    uint32_t budget = 200000U;

    RCC_CR |= 1U;

    while(!(RCC_CR & 2U))
    {
        if(--budget == 0U)
            return 0U;
    }

    /* HSI 8 MHz */

    RCC_CFGR &= ~3U;

    budget = 200000U;

    while(RCC_CFGR & (3U << 2U))
    {
        if(--budget == 0U)
            return 0U;
    }

    RCC_CFGR &= ~(
        (0xFU << 4U) |
        (7U << 8U)
    );

    SYST_RVR = 7999U;
    SYST_CVR = 0U;
    SYST_CSR = 7U;

    return 1U;
}

